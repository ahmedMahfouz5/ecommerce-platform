export interface Product {
  id: string;
  /** Product name. */
  title: string;
  description: string;
  /** Current price in USD. */
  price: number;
  /** Category tags, e.g. `["dairy", "milk"]`. */
  categories: string[];
  /** Raw S3 object keys (e.g. `"products/<uuid>/<uuid>.webp"`). */
  image: string[];
  /** Product rating from 1 to 5. */
  rating: number;
  /** Current stock quantity. */
  amount: number;
  /** Top-level section, e.g. `"grocery"`, `"clothing"`. */
  shop_category: string;
  /** Unit of sale, e.g. `"kg"`, `"liter"`, `"pc(s)"`. */
  unit_of_measure: string;
  /** Original price before discount. When present, the product is on sale. */
  oldPrice: number | null;
  /** Available garment sizes (optional). */
  sizes: string[] | null;
  /** Color variants (optional). */
  colors: string[] | null;
  /** Book authors for `shop_category = "books"` (optional). */
  authors: string[] | null;
  /** Public CloudFront CDN URLs generated by the backend — use these in <img> tags. */
  image_download_url: string[] | null;
  /** True when `oldPrice` is set. */
  on_sale: boolean;
  created_at: string;
  updated_at: string;
}

export interface ProductListResponse {
  items: Product[];
  total: number;
  page: number;
  page_size: number;
  total_pages: number;
}

export interface ProductCreate {
  title: string;
  description: string;
  price: number;
  categories: string[];
  image: string[];
  rating: number;
  amount: number;
  shop_category: string;
  unit_of_measure: string;
  oldPrice?: number | null;
  sizes?: string[] | null;
  colors?: string[] | null;
  authors?: string[] | null;
}

export interface ProductUpdate {
  title?: string;
  description?: string | null;
  price?: number;
  categories?: string[];
  image?: string[];
  rating?: number;
  amount?: number;
  shop_category?: string;
  unit_of_measure?: string;
  oldPrice?: number | null;
  sizes?: string[] | null;
  colors?: string[] | null;
  authors?: string[] | null;
}
